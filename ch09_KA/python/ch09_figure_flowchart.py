def box(x,y,w,h,t,ec=BLUE,fc='white',fs=10,shape='r'):
    if shape=='r': ax.add_patch(FancyBboxPatch((x-w/2,y-h/2),w,h,boxstyle='round,pad=0.08',fc=fc,ec=ec,lw=2,zorder=2))
    elif shape=='o': ax.add_patch(FancyBboxPatch((x-w/2,y-h/2),w,h,boxstyle='round,pad=0.08,rounding_size=0.45',fc=fc,ec=ec,lw=2,zorder=2))
    else: ax.add_patch(Polygon([(x,y+h/2),(x+w/2,y),(x,y-h/2),(x-w/2,y)],closed=True,fc=fc,ec=PURPLE,lw=2,zorder=2))
    ax.text(x,y,t,ha='center',va='center',fontsize=fs,zorder=3)
def seg(pts,col='black',arrow=True,lab=None,lp=None):
    for a,b in zip(pts[:-2],pts[1:-1]): ax.plot([a[0],b[0]],[a[1],b[1]],color=col,lw=2,zorder=1)
    a,b=pts[-2],pts[-1]
    if arrow: ax.annotate('',xy=b,xytext=a,arrowprops=dict(arrowstyle='-|>',lw=2,color=col),zorder=1)
    else: ax.plot([a[0],b[0]],[a[1],b[1]],color=col,lw=2)
    if lab: ax.text(lp[0],lp[1],lab,fontsize=10,color=col,ha='center',va='center',bbox=dict(fc='white',ec='none',pad=0.1),zorder=4)
